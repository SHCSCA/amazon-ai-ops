const fs = require('fs');
const path = require('path');

function fail(message) {
  console.error(`[FAIL] ${message}`);
  process.exitCode = 1;
}

function pass(message) {
  console.log(`[PASS] ${message}`);
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function hasText(value) {
  return typeof value === 'string' && value.trim().length > 0;
}

function assertNoSecret(value, location) {
  const text = JSON.stringify(value || '');
  if (
    /sk-[A-Za-z0-9_-]{16,}/.test(text)
    || /Bearer\s+[A-Za-z0-9._~+/=-]{16,}/i.test(text)
    || /deepseek[_-]?api[_-]?key["']?\s*[:=]\s*["'][^"']+/i.test(text)
    || /deepseek-[A-Za-z0-9_-]{12,}/i.test(text)
  ) {
    fail(`${location} appears to contain an API key`);
  }
}

function isRealReportSourceFile(filePath) {
  return /\.(xlsx|xls|csv)$/i.test(String(filePath || '').trim().split(/[?#]/)[0]);
}

function positiveNumber(value) {
  const parsed = Number(value);
  return Number.isFinite(parsed) && parsed > 0;
}

function assertEquals(actual, expected, label) {
  if (actual === expected) {
    pass(label);
  } else {
    fail(`${label} expected ${JSON.stringify(expected)}, got ${JSON.stringify(actual)}`);
  }
}

const filePath = process.argv[2];
if (!filePath) {
  console.error('Usage: node scripts/verify-ad-ai-explanation-evidence.js <evidence-json>');
  process.exit(1);
}

if (!fs.existsSync(filePath)) {
  console.error(`Evidence file not found: ${filePath}`);
  process.exit(1);
}

const evidence = readJson(filePath);

if (!['ad-ai-explanation', 'installed-ad-ai-explanation'].includes(evidence.kind)) {
  fail(`unexpected evidence kind: ${evidence.kind || '<missing>'}`);
} else {
  pass('evidence kind is ad AI explanation');
}

if (evidence.status === 'PASS') {
  pass('evidence status is PASS');
} else {
  fail(`evidence status is not PASS: ${evidence.status || '<missing>'}`);
}

if (evidence.readinessImpact === 'NO_FINAL_READINESS_CREDIT') {
  fail('structural/mock evidence cannot satisfy ad AI explanation readiness');
}

assertEquals(evidence.runtimeMode, 'packaged-app', 'evidence was generated by packaged app');

const safety = evidence.safety || {};
assertEquals(safety.adAiExplanationOnly, true, 'evidence mode is ad-ai-explanation only');
assertEquals(safety.adWriteActionsPerformed, false, 'no ad write actions were performed');
assertEquals(safety.full8Started, false, 'full-8 report collection was not started');
if (Array.isArray(safety.reportTypesRequested) && safety.reportTypesRequested.length === 0) {
  pass('no Lingxing report downloads were requested');
} else {
  fail('ad AI explanation evidence must not request Lingxing report downloads');
}

const ai = evidence.ai || {};
if (ai.keyPresent === true && hasText(ai.baseUrl) && hasText(ai.model)) {
  pass('AI provider metadata proves real key/base/model were configured');
} else {
  fail('AI provider metadata is incomplete or keyPresent is not true');
}
assertEquals(ai.testSuccess, true, 'AI connection test succeeded before recommendation generation');

if (evidence.adAiExplanation?.settingsRestored === true) {
  pass('AI settings were restored after evidence run');
} else if (evidence.aiSettingsChanged === false && ai.storedKeyAccepted === true) {
  pass('AI settings were not modified during evidence run');
} else {
  fail('AI settings restore proof is missing or failed');
}

const recommendations = Array.isArray(evidence.recommendations) ? evidence.recommendations : [];
if (recommendations.length > 0) {
  pass(`recommendation explanation count = ${recommendations.length}`);
} else {
  fail('at least one AI-explained recommendation is required');
}

for (const [index, rec] of recommendations.entries()) {
  const prefix = `recommendations[${index}]`;
  if (hasText(rec.storeName) && hasText(rec.marketplaceCode) && hasText(rec.asin)) {
    pass(`${prefix} has store/site/ASIN context`);
  } else {
    fail(`${prefix} is missing store/site/ASIN context`);
  }
  if (hasText(rec.entityId) && hasText(rec.entityName) && hasText(rec.actionType)) {
    pass(`${prefix} has ad entity/action context`);
  } else {
    fail(`${prefix} is missing ad entity/action context`);
  }
  if (rec.explanationSource === 'ai') {
    pass(`${prefix} explanation source is AI`);
  } else {
    fail(`${prefix} explanationSource is not ai`);
  }
  if (hasText(rec.aiExplanation) && rec.aiExplanation.length >= 12) {
    pass(`${prefix} has AI explanation text`);
  } else {
    fail(`${prefix} AI explanation is missing or too short`);
  }
  if (rec.aiFallbackReason) {
    fail(`${prefix} has fallback reason; AI explanation did not fully pass`);
  }
  if (hasText(rec.aiModel)) {
    pass(`${prefix} records AI model`);
  } else {
    fail(`${prefix} is missing AI model`);
  }
  if (!hasText(rec.metricDate)) {
    fail(`${prefix} is missing metric date`);
  }
  if (!hasText(rec.currentValue)) {
    fail(`${prefix} is missing current value`);
  }
  if (!hasText(rec.recommendedValue)) {
    fail(`${prefix} is missing executable recommended value`);
  }
  const sourceFiles = Array.isArray(rec.sourceFiles) ? rec.sourceFiles : [];
  if (sourceFiles.length > 0 && sourceFiles.every(isRealReportSourceFile)) {
    pass(`${prefix} has real report source file`);
  } else {
    fail(`${prefix} is missing real report source file`);
  }
  if (positiveNumber(rec.sourceRow)) {
    pass(`${prefix} has original report source row`);
  } else {
    fail(`${prefix} is missing original report source row`);
  }
  assertNoSecret(rec, prefix);
}

assertNoSecret(evidence, 'evidence');

if (process.exitCode) {
  console.error('\nNEEDS_WORK: Ad AI explanation evidence is incomplete.');
  process.exit(process.exitCode);
}

console.log(`\nAD_AI_EXPLANATION verified: ${path.resolve(filePath)}`);
